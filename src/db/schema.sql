-- =============================================
-- Users
-- =============================================
CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    date_of_birth DATE,
    national_id_number VARCHAR(50) NOT NULL UNIQUE,
    phone_number VARCHAR(30) NOT NULL,
    secondary_phone_number VARCHAR(30),
    photo TEXT,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    roles user_role[] NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT users_roles_not_empty
        CHECK (cardinality(roles) > 0)
);

-- =============================================
-- Clinic Owners
-- =============================================
CREATE TABLE IF NOT EXISTS clinic_owners (
    owner_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE
        REFERENCES users(user_id)
);



-- =============================================
-- Clinics
-- =============================================
CREATE TABLE IF NOT EXISTS clinics (
    clinic_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinic_name VARCHAR(150) NOT NULL,
    address TEXT NOT NULL,
    phone_number VARCHAR(30) NOT NULL,
    secondary_phone_number VARCHAR(30),
    email VARCHAR(255) NOT NULL,
    logo TEXT,
    owner_id INTEGER NOT NULL UNIQUE
        REFERENCES clinic_owners(owner_id)
);

-- =============================================
-- Doctors
-- =============================================
CREATE TABLE IF NOT EXISTS doctors (
    doctor_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE
        REFERENCES users(user_id),
    speciality VARCHAR(150) NOT NULL,
    default_consultation_fee NUMERIC(10, 2) NOT NULL
        CHECK (default_consultation_fee >= 0),
    default_slot_duration INTEGER NOT NULL
        CHECK (default_slot_duration > 0)
);

-- =============================================
-- Receptionists
-- =============================================
CREATE TABLE IF NOT EXISTS receptionists (
    receptionist_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE
        REFERENCES users(user_id)
);


-- =============================================
-- Working Hours
-- =============================================
CREATE TABLE IF NOT EXISTS working_hours (
    working_hours_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    doctor_id INTEGER REFERENCES doctors(doctor_id),
    receptionist_id INTEGER REFERENCES receptionists(receptionist_id),

    day_of_week day_of_week_type NOT NULL,
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    from_time TIME,
    to_time TIME,

    CONSTRAINT working_hours_one_owner
        CHECK (
            (doctor_id IS NOT NULL AND receptionist_id IS NULL)
            OR
            (doctor_id IS NULL AND receptionist_id IS NOT NULL)
        ),

    CONSTRAINT working_hours_valid_times
        CHECK (
            (is_enabled = FALSE)
            OR
            (from_time IS NOT NULL
             AND to_time IS NOT NULL
             AND from_time < to_time)
        ),

    CONSTRAINT working_hours_doctor_day_unique
        UNIQUE (doctor_id, day_of_week),

    CONSTRAINT working_hours_receptionist_day_unique
        UNIQUE (receptionist_id, day_of_week)
);


-- =============================================
-- Patients
