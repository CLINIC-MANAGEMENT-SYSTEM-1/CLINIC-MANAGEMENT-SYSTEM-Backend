-- =============================================
-- Patient Clinical Profiles
-- =============================================
CREATE TABLE IF NOT EXISTS patient_clinical_profiles (
    patient_id INTEGER PRIMARY KEY
        REFERENCES patients(patient_id),

    chronic_diseases TEXT,
    allergies TEXT,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_by_doctor_id INTEGER
        REFERENCES doctors(doctor_id)
);


-- =============================================
-- Appointments
-- =============================================
CREATE TABLE IF NOT EXISTS appointments (
    appointment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    patient_id INTEGER NOT NULL
        REFERENCES patients(patient_id),

    doctor_id INTEGER NOT NULL
        REFERENCES doctors(doctor_id),

    start_datetime TIMESTAMPTZ,
    end_datetime TIMESTAMPTZ,
    checked_in_at TIMESTAMPTZ,

    complaint TEXT,

    appointment_type appointment_type NOT NULL DEFAULT 'normal',
    status appointment_status NOT NULL DEFAULT 'scheduled',

    cancellation_reason TEXT,
    scheduling_notes TEXT,

    cancelled_by_user_id INTEGER
        REFERENCES users(user_id),

    
    CONSTRAINT appointments_valid_times
        CHECK (
            (
                appointment_type = 'normal'
                AND start_datetime IS NOT NULL
                AND end_datetime IS NOT NULL
                AND end_datetime > start_datetime
            )
            OR
            (
                appointment_type = 'emergency'
                AND (
                    (
                        start_datetime IS NULL
                        AND end_datetime IS NULL
                    )
                    OR
                    (
                        start_datetime IS NOT NULL
                        AND end_datetime IS NOT NULL
                        AND end_datetime > start_datetime
                    )
                )
            )
        )

);



-- =============================================
-- Medical Visits
-- =============================================
CREATE TABLE IF NOT EXISTS medical_visits (
    medical_visit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    appointment_id INTEGER NOT NULL UNIQUE
        REFERENCES appointments(appointment_id),

    diagnoses TEXT,
    prescribed_medicines TEXT,
    procedures_and_diagnostics_performed TEXT,
    additional_clinical_notes TEXT,

    next_step next_step_type NOT NULL,

    follow_up_reason TEXT,
    suggested_follow_up_date DATE,

    CONSTRAINT medical_visits_follow_up_required
        CHECK (
            next_step <> 'follow_up_review_appointment_required'
            OR (
                follow_up_reason IS NOT NULL
                AND LENGTH(TRIM(follow_up_reason)) > 0
                AND suggested_follow_up_date IS NOT NULL
            )
        )
);


-- =============================================
-- Visit Billings
-- =============================================
CREATE TABLE IF NOT EXISTS visit_billings (
    billing_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    appointment_id INTEGER NOT NULL UNIQUE
        REFERENCES appointments(appointment_id),

    original_fee NUMERIC(10, 2) NOT NULL
        CHECK (original_fee >= 0),

    adjusted_due NUMERIC(10, 2) NOT NULL
        CHECK (adjusted_due >= 0)
);


-- =============================================
-- Financial Transactions
-- =============================================
CREATE TABLE IF NOT EXISTS financial_transactions (
    transaction_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    billing_id INTEGER NOT NULL
        REFERENCES visit_billings(billing_id),

    transaction_type transaction_type NOT NULL,

    amount NUMERIC(10, 2) NOT NULL
        CHECK (amount >= 0),

    transaction_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    payment_method payment_method_type,

    recorded_by_user_id INTEGER
        REFERENCES users(user_id),

    reason TEXT,
    transaction_notes TEXT,

    adjustment_direction adjustment_direction_type,

    approved_by_doctor_id INTEGER
        REFERENCES doctors(doctor_id),

    related_transaction_id INTEGER
        REFERENCES financial_transactions(transaction_id),

    
    CONSTRAINT financial_transactions_adjustment_direction
        CHECK (
            (
                transaction_type = 'adjustment'
                AND adjustment_direction IS NOT NULL
            )
            OR
            (
                transaction_type <> 'adjustment'
                AND adjustment_direction IS NULL
            )
        ),

    CONSTRAINT financial_transactions_payment_method
        CHECK (
            transaction_type <> 'payment'
            OR payment_method IS NOT NULL
        ),

    CONSTRAINT financial_transactions_waiver_details
        CHECK (
            transaction_type <> 'waiver'
            OR (
                reason IS NOT NULL
                AND LENGTH(TRIM(reason)) > 0
                AND approved_by_doctor_id IS NOT NULL
            )
        ),

    CONSTRAINT financial_transactions_reason_required
        CHECK (
            transaction_type NOT IN (
                'waiver',
                'adjustment',
                'additional_charge'
            )
            OR (
                reason IS NOT NULL
                AND LENGTH(TRIM(reason)) > 0
            )
        )
        

);


-- =============================================
-- Prevent overlapping appointments for a doctor
-- =============================================

CREATE EXTENSION IF NOT EXISTS btree_gist;


DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'appointments_no_overlapping_doctor_slots'
          AND conrelid = 'appointments'::regclass
    ) THEN
        ALTER TABLE appointments
        ADD CONSTRAINT appointments_no_overlapping_doctor_slots
        EXCLUDE USING gist (
            doctor_id WITH =,
            tstzrange(start_datetime, end_datetime, '[)') WITH &&
        )
        WHERE (
            appointment_type = 'normal'
            AND start_datetime IS NOT NULL
            AND end_datetime IS NOT NULL
            AND status NOT IN ('cancelled', 'no_show')
        );
    END IF;
END $$;


